#!/usr/bin/env python
"""R16 checkpoint 1 judgement: continue iff  mean W2 of our generators <= 1.25 x the worse (larger W2)
of the two baselines (CFGen, scLDM, generated by us from their public checkpoints), all on HLCA test, uncond, table2_metrics v3.
Our generators: every runs/r16/ckpt1/ckpt1_uncond_s<trainseed>_test.json present (seed 1 20260625, seed 2 20260627, seed 3 20260630);
the seeds used are listed. Stops if either baseline is missing or if any file's settings differ from seed 1's. Writes OUT.json/.md.
    python ckpt1_judge.py OUT_PREFIX
"""
import hashlib, json, os, sys
import numpy as np
W = "./work"; D = f"{W}/runs/r16/ckpt1"; out = sys.argv[1]
sha = lambda f: hashlib.sha256(open(f, "rb").read()).hexdigest()
S = {"seed 1": 20260625, "seed 2": 20260627, "seed 3": 20260630}
ours = {k: f"{D}/ckpt1_uncond_s{v}_test.json" for k, v in S.items() if os.path.exists(f"{D}/ckpt1_uncond_s{v}_test.json")}
# v2 (11-10 14:3x): scLDM removed from the HLCA baselines; the verdict compares against CFGen only.
base = {"CFGen": f"{D}/ckpt1_uncond_cfgen_test.json"}
miss = [k for k, f in base.items() if not os.path.exists(f)]; assert not miss, f"baseline missing: {miss}"
J = {k: json.load(open(f)) for k, f in {**ours, **base}.items()}; ref = J["seed 1"]["settings"]
for k, j in J.items():
    assert j["settings"] == ref, f"{k}: settings differ from seed 1"
    assert j["inputs"]["script_sha256"].startswith("e690a6e4"), k
w2 = {k: J[k]["uncond"]["W2"] for k in J}; our = [w2[k] for k in ours]
worse = max(base, key=lambda k: w2[k]); thr = 1.25 * w2[worse]; mean = float(np.mean(our)); ok = mean <= thr
rr = json.load(open(f"{D}/ref_realval_vs_test.json"))["uncond"]
res = {"rule": "pre-reg #6: mean W2 (ours) <= 1.25 x the worse baseline (larger W2); since 11-10 14:24 the only HLCA baseline here is CFGen",
       "ours_seeds": list(ours), "ours_W2": {k: w2[k] for k in ours}, "ours_W2_mean": mean, "baseline_W2": {k: w2[k] for k in base},
       "worse_baseline": worse, "threshold": thr, "pass": bool(ok), "margin_rel": (thr - mean) / thr,
       "per_seed_pass": {k: bool(w2[k] <= thr) for k in ours},
       "note": "the task notes 11-10 10:09: the verdict uses the seeds present at judgement; a seed that lands later is reported only, the verdict does not change",
       "metrics": {k: J[k]["uncond"] for k in J}, "reference_real_val_vs_test": rr,
       "files": {k: {"file": f, "sha256": sha(f)} for k, f in {**ours, **base}.items()}, "script_sha256": sha(__file__)}
json.dump(res, open(out + ".json", "w"), indent=1)
L = ["| generator | W2 | MMD² | 1-NN | precision | recall |", "|---|---|---|---|---|---|"]
for k in list(ours) + list(base):
    u = J[k]["uncond"]; L.append(f"| {'CRNDiff ' + k if k in ours else k} | {u['W2']:.3f} | {u['MMD2']:.5f} | {u['1NN']:.3f} | {u['precision']:.3f} | {u['recall']:.3f} |")
L.append(f"| real val vs test (reference) | {rr['W2']:.3f} | {rr['MMD2']:.5f} | {rr['1NN']:.3f} | {rr['precision']:.3f} | {rr['recall']:.3f} |")
L += ["", f"- our W2 mean ({len(our)} seeds:{','.join(ours)}) = {mean:.3f}; worse baseline {worse} W2 {w2[worse]:.3f}, threshold 1.25× = {thr:.3f}.",
      f"- verdict:**{'pass' if ok else 'fails'}**({'below' if ok else 'above'}threshold {abs(thr - mean) / thr * 100:.1f}%).",
      "- per seed:" + ",".join(f"{k} W2 {w2[k]:.3f} {'pass' if w2[k] <= thr else 'fails'}" for k in ours) + "(whether each passes is listed only; the verdict uses the mean)."]
open(out + ".md", "w").write("\n".join(L) + "\n"); print("\n".join(L))
